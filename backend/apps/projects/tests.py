class ProjectModelTests(TestCase):
    def setUp(self):
        self.org = Organization.objects.create(name="Acme")

    def test_slug_autogenerated_and_scoped_per_org(self):
        p = Project.objects.create(organization=self.org, name="Website")
        self.assertEqual(p.slug, "website")

    def test_same_slug_allowed_in_different_orgs(self):
        other = Organization.objects.create(name="Globex")
        a = Project.objects.create(organization=self.org, name="App")
        b = Project.objects.create(organization=other, name="App")
        self.assertEqual(a.slug, "app")
        self.assertEqual(b.slug, "app")  # different org, no collision

    def test_slug_collision_within_org(self):
        a = Project.objects.create(organization=self.org, name="App")
        b = Project.objects.create(organization=self.org, name="App")
        self.assertEqual(a.slug, "app")
        self.assertEqual(b.slug, "app-2")

    def test_duplicate_slug_in_same_org_rejected(self):
        Project.objects.create(organization=self.org, name="App", slug="app")
        with self.assertRaises(IntegrityError):
            Project.objects.create(organization=self.org, name="Other", slug="app")

    def test_ensure_default_workspace_is_idempotent(self):
        p = Project.objects.create(organization=self.org, name="App")
        w1 = p.ensure_default_workspace()
        w2 = p.ensure_default_workspace()
        self.assertEqual(w1, w2)
        self.assertEqual(p.workspaces.count(), 1)
        self.assertTrue(w1.is_default)
        self.assertEqual(w1.organization, self.org)


class ProjectAPITests(TestCase):
    def setUp(self):
        # org_a: alice is owner. org_b: bob is owner. carol: member of org_a only.
        self.alice = User.objects.create_user(email="alice@x.com", password="pw12345!")
        self.bob = User.objects.create_user(email="bob@x.com", password="pw12345!")
        self.carol = User.objects.create_user(email="carol@x.com", password="pw12345!")

        self.org_a = Organization.objects.create(name="Org A")
        self.org_b = Organization.objects.create(name="Org B")
        self.org_a.add_member(self.alice, role=Role.OWNER)
        self.org_a.add_member(self.carol, role=Role.MEMBER)
        self.org_b.add_member(self.bob, role=Role.OWNER)

        self.proj_a = Project.objects.create(organization=self.org_a, name="A Project")
        self.proj_b = Project.objects.create(organization=self.org_b, name="B Project")

    def test_list_requires_authentication(self):
        resp = self.client.get(reverse("projects:list"))
        self.assertEqual(resp.status_code, 401)

    def test_list_only_shows_own_org_projects(self):
        self.client.force_login(self.alice)
        resp = self.client.get(reverse("projects:list"))
        self.assertEqual(resp.status_code, 200)
        ids = [p["id"] for p in resp.json()]
        self.assertEqual(ids, [self.proj_a.id])

    def test_cannot_retrieve_other_tenants_project(self):
        self.client.force_login(self.alice)
        resp = self.client.get(reverse("projects:detail", args=[self.proj_b.id]))
        self.assertEqual(resp.status_code, 404)

    def test_owner_can_create_project_and_gets_default_workspace(self):
        self.client.force_login(self.alice)
        resp = self.client.post(
            reverse("projects:list"),
            {"organization": self.org_a.id, "name": "New Site", "mode": "build"},
            content_type="application/json",
        )
        self.assertEqual(resp.status_code, 201, resp.content)
        body = resp.json()
        self.assertEqual(body["slug"], "new-site")
        self.assertEqual(body["created_by"], self.alice.id)
        created = Project.objects.get(id=body["id"])
        self.assertEqual(created.workspaces.filter(is_default=True).count(), 1)

    def test_member_cannot_create_project(self):
        # carol is only a plain member of org_a -> not in manageable orgs.
        self.client.force_login(self.carol)
        resp = self.client.post(
            reverse("projects:list"),
            {"organization": self.org_a.id, "name": "Nope"},
            content_type="application/json",
        )
        self.assertEqual(resp.status_code, 400)

    def test_cannot_create_project_in_foreign_org(self):
        self.client.force_login(self.alice)
        resp = self.client.post(
            reverse("projects:list"),
            {"organization": self.org_b.id, "name": "Sneaky"},
            content_type="application/json",
        )
        self.assertEqual(resp.status_code, 400)


class BuildApiTests(TestCase):
    """The core mobile loop: describe an app -> build -> poll status."""

    def setUp(self):
        self.owner = User.objects.create_user(
            email="builder@x.com", password="pw12345!", full_name="Builder"
        )
        self.owner.email_verified = True
        self.owner.save(update_fields=["email_verified"])
        self.org = Organization.objects.create(name="Build Org")
        self.org.add_member(self.owner, role=Role.OWNER)

    def tearDown(self):
        # A build writes generated files into the (temp, under tests) workspaces
        # root keyed by project id. Project ids repeat across tests, so clear the
        # root here to avoid leaking files into other tests that reuse an id.
        import shutil

        from django.conf import settings

        shutil.rmtree(settings.BOLDRON_WORKSPACES_ROOT, ignore_errors=True)

    def _auth(self, user=None):
        from apps.accounts.api import issue_tokens

        return {"HTTP_AUTHORIZATION": f"Bearer {issue_tokens(user or self.owner)['access']}"}

    def test_build_from_brief_creates_project_and_runs_pipeline(self):
        from apps.orchestrator.models import AgentTask

        resp = self.client.post(
            reverse("projects:build"),
            data={"brief": "Build an online store for my shop with products and checkout"},
            content_type="application/json",
            **self._auth(),
        )
        self.assertEqual(resp.status_code, 201)
        body = resp.json()
        self.assertIn("project", body)
        self.assertEqual(body["project"]["name"], "Online Store")
        pid = body["project"]["id"]
        # The agent pipeline was queued (runs inline under tests).
        self.assertTrue(AgentTask.objects.filter(project_id=pid).exists())

    def test_build_requires_verified_email(self):
        self.owner.email_verified = False
        self.owner.save(update_fields=["email_verified"])
        resp = self.client.post(
            reverse("projects:build"),
            data={"brief": "Build a CRM"},
            content_type="application/json",
            **self._auth(),
        )
        self.assertEqual(resp.status_code, 403)

    def test_build_rejects_empty_brief(self):
        resp = self.client.post(
            reverse("projects:build"),
            data={"brief": "   "},
            content_type="application/json",
            **self._auth(),
        )
        self.assertEqual(resp.status_code, 400)

    def test_build_rejects_unmanaged_org(self):
        other = Organization.objects.create(name="Not Mine")
        resp = self.client.post(
            reverse("projects:build"),
            data={"brief": "Build a CRM", "organization": other.id},
            content_type="application/json",
            **self._auth(),
        )
        self.assertEqual(resp.status_code, 400)

    def test_build_status_reports_progress_and_steps(self):
        pid = self.client.post(
            reverse("projects:build"),
            data={"brief": "Build a CRM with contacts and deals"},
            content_type="application/json",
            **self._auth(),
        ).json()["project"]["id"]
        resp = self.client.get(
            reverse("projects:build-status", args=[pid]), **self._auth()
        )
        self.assertEqual(resp.status_code, 200)
        body = resp.json()
        self.assertIn("state", body)
        self.assertIn("progress", body)
        self.assertIsInstance(body["steps"], list)
        self.assertTrue(body["steps"])  # pipeline steps are present
        self.assertIn("credits", body)

    def test_build_status_hidden_from_non_members(self):
        pid = self.client.post(
            reverse("projects:build"),
            data={"brief": "Build a CRM"},
            content_type="application/json",
            **self._auth(),
        ).json()["project"]["id"]
        outsider = User.objects.create_user(email="out@x.com", password="pw12345!")
        resp = self.client.get(
            reverse("projects:build-status", args=[pid]), **self._auth(outsider)
        )
        self.assertEqual(resp.status_code, 404)


